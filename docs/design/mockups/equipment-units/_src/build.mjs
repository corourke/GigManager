// Builds the #162 mockups: each page module in ./pages renders to a self-contained
// HTML file (Tailwind compiled and inlined) in the folder above, and a 1440 px PNG
// in ../png. Usage (from this folder):
//   npm i --no-save @tailwindcss/cli@4.1.13 tailwindcss@4.1.13 playwright-core@1.56.1
//   node build.mjs            # HTML + PNG (Chromium from PLAYWRIGHT_BROWSERS_PATH)
//   node build.mjs --no-png   # HTML only
import { readdirSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..');
const staging = join(here, '_build', 'staging');
rmSync(join(here, '_build'), { recursive: true, force: true });
mkdirSync(staging, { recursive: true });
mkdirSync(join(out, 'png'), { recursive: true });

const doc = (title, body, css) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<!-- Mockup for GitHub issue #162. Generated by _src/build.mjs from _src/pages; edit those, not this file. -->
<style>${css}</style>
</head>
<body class="p-6">
${body}
</body>
</html>
`;

const pages = [];
for (const f of readdirSync(join(here, 'pages')).filter((f) => f.endsWith('.mjs')).sort()) {
  const mod = await import(pathToFileURL(join(here, 'pages', f)).href);
  const { name, title, html } = mod.default();
  pages.push({ name, title, html });
  writeFileSync(join(staging, `${name}.html`), html);
}

const cli = join(here, 'node_modules', '.bin', 'tailwindcss');
const cssFile = join(here, '_build', 'out.css');
execFileSync(cli, ['-i', join(here, 'theme.css'), '-o', cssFile, '--minify'], { cwd: here, stdio: 'inherit' });
const css = readFileSync(cssFile, 'utf8');

for (const p of pages) writeFileSync(join(out, `${p.name}.html`), doc(p.title, p.html, css));
console.log(`wrote ${pages.length} pages (${Math.round(css.length / 1024)} KB CSS each)`);

if (!process.argv.includes('--no-png')) {
  const require = createRequire(import.meta.url);
  const { chromium } = require('playwright-core');
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  // index last: it shows the other pages' PNGs as thumbnails
  for (const p of [...pages].sort((a, b) => (a.name === 'index') - (b.name === 'index'))) {
    await page.goto(pathToFileURL(join(out, `${p.name}.html`)).href);
    // Report anything wider than the viewport (horizontal overflow is a layout bug here).
    const wide = await page.evaluate(() => document.documentElement.scrollWidth);
    if (wide > 1440) console.warn(`  ${p.name}: page is ${wide}px wide`);
    await page.screenshot({ path: join(out, 'png', `${p.name}.png`), fullPage: true });
  }
  await browser.close();
  console.log('wrote PNGs');
}
rmSync(join(here, '_build'), { recursive: true, force: true });
